import { test, expect, PASSWORD, newEmail, mailCode, lastMail, createSeller, setStatus, uiLogin, dismissPasskeyOffer, expectNoSeriousA11y } from './helpers'

test('signup wizard through the pending screen', async ({ page, request }) => {
  const email = newEmail()
  await page.goto('/signup')
  await expectNoSeriousA11y(page)
  await expect(page.getByRole('progressbar')).toHaveAttribute('aria-valuenow', '1')
  // Account
  await page.getByLabel('Email').fill(email.replace('@example.com', '@gmial.com'))
  await page.getByLabel('Password', { exact: true }).fill(PASSWORD)
  await page.getByLabel('Confirm password').fill(PASSWORD)
  await expect(page.getByText('Did you mean')).toBeVisible()
  await page.getByRole('button', { name: 'gmail.com' }).click()
  await expect(page.getByLabel('Email')).toHaveValue(email.replace('@example.com', '@gmail.com'))
  await page.getByLabel('Email').fill(email)
  await page.getByRole('button', { name: 'Create account' }).click()
  await expect(page.getByText('You must accept the Terms to continue')).toBeVisible()
  await page.getByLabel(/I agree to the/).check()
  await page.getByRole('button', { name: 'Create account' }).click()
  // Verify
  await expect(page.getByRole('heading', { name: 'Verify your email' })).toBeVisible()
  await expectNoSeriousA11y(page)
  await expect(page.getByLabel('Email')).toHaveValue(email) // public step: no session yet
  await expect(page.getByRole('button', { name: /Resend code in \d+s/ })).toBeDisabled()
  await page.getByLabel('Verification code').fill('000000')
  await page.getByRole('button', { name: 'Verify' }).click()
  await expect(page.getByText("That code isn't right or has expired.")).toBeVisible()
  await page.getByLabel('Verification code').fill(await mailCode(request, email))
  await page.getByRole('button', { name: 'Verify' }).click()
  // Business
  await expect(page.getByRole('heading', { name: 'Business details' })).toBeVisible()
  await expectNoSeriousA11y(page)
  await page.getByLabel('Business name').fill('Acme Bakery')
  await page.getByLabel('Contact name').fill('Dana Seller')
  await page.getByLabel('Phone').fill('+1 555 123 4567')
  await page.getByLabel('Address line 1').fill('1 Main St')
  await page.getByLabel('City').fill('Brooklyn')
  await page.getByLabel('Postal code').fill('11201')
  await page.getByLabel(/Country/).fill('US')
  await expect(page.getByLabel(/receive text messages/)).not.toBeChecked()
  await page.getByRole('button', { name: 'Continue' }).click()
  // Kosher: branching
  await expect(page.getByRole('heading', { name: 'Food & kosher' })).toBeVisible()
  await expectNoSeriousA11y(page)
  await expect(page.getByText('Is your food kosher?')).toHaveCount(0)
  await page.getByRole('group', { name: 'Do you sell food?' }).getByLabel('Yes').check()
  await page.getByRole('group', { name: 'Is your food kosher?' }).getByLabel('Yes').check()
  await expect(page.getByText('Kosher certifying agency')).toBeVisible()
  await page.getByRole('group', { name: 'Is your food kosher?' }).getByLabel('No').check()
  await expect(page.getByText('Kosher certifying agency')).toHaveCount(0)
  await page.getByRole('group', { name: 'Do you sell food?' }).getByLabel('No').check()
  await expect(page.getByText('Is your food kosher?')).toHaveCount(0)
  await page.getByRole('button', { name: 'Continue' }).click()
  // Review (draft survives a reload)
  await expect(page.getByRole('heading', { name: 'Review your application' })).toBeVisible()
  await expectNoSeriousA11y(page)
  await page.reload()
  await expect(page.getByText('Acme Bakery')).toBeVisible()
  await page.getByRole('button', { name: 'Submit application' }).click()
  await expect(page.getByText('You must accept the Seller Agreement to submit.')).toBeVisible()
  await page.getByLabel(/Seller Agreement/).check()
  await page.getByRole('button', { name: 'Submit application' }).click()
  // Pending
  await expect(page.getByRole('heading', { name: 'Your application is pending' })).toBeVisible()
  await expectNoSeriousA11y(page)
  await expect(page.getByText(/Management will reach out/)).toBeVisible()
  await expect(page.getByRole('list', { name: 'Application status' }).getByRole('listitem')).toHaveCount(4)
  await expect(page.getByRole('link', { name: 'Visit marketplace' })).toBeVisible()
  await page.getByRole('link', { name: 'Guest mode' }).click()
  await expect(page.getByRole('heading', { name: 'Guest mode' })).toBeVisible()
  expect(await lastMail(request, email, 'application-received')).toContain('Acme Bakery')
})

test('admin approves via API; login, redirect-back and logout', async ({ page, request }) => {
  const s = await createSeller(request)
  const biz = await request.post('/api/v1/auth/login', { data: { email: s.email, password: s.password } })
  const { accessToken } = await biz.json()
  const auth = { Authorization: `Bearer ${accessToken}` }
  await request.put('/api/v1/seller/application/business', { headers: auth, data: { vendorName: 'Acme', contactName: 'D', contactPhone: '+1 555 123 4567', addressLine1: '1 Main', city: 'NYC', postalCode: '10001', country: 'US', smsOptIn: false } })
  await request.put('/api/v1/seller/application/kosher', { headers: auth, data: { answers: { sells_food: 'no' } } })
  expect((await request.post('/api/v1/seller/application/submit', { headers: auth, data: { acceptSellerAgreement: true } })).ok()).toBeTruthy()
  await setStatus(request, s.sellerId, 'Approved')
  expect(await lastMail(request, s.email, 'approved')).toContain('approved')

  // anonymous visit to a protected page -> login -> back to that page
  await page.goto('/settings/security')
  await expect(page).toHaveURL(/\/login\?next=%2Fsettings%2Fsecurity/)
  await expectNoSeriousA11y(page)
  await uiLogin(page, s.email)
  await dismissPasskeyOffer(page)
  await expect(page).toHaveURL(/\/settings\/security$/)
  await expect(page.getByRole('heading', { name: 'Change password' })).toBeVisible()
  await expectNoSeriousA11y(page)
  // pending screen shows the Approved stage
  await page.goto('/')
  await expect(page.getByRole('list', { name: 'Application status' }).getByText('Approved').locator('..')).toHaveAttribute('aria-current', 'step')
  // reload keeps the session (refresh cookie); logout ends it
  await page.reload()
  await expect(page.getByRole('heading', { name: 'Your application is approved' })).toBeVisible()
  await page.getByRole('button', { name: 'Log out' }).click()
  await expect(page).toHaveURL(/\/login/)
  await page.goto('/')
  await expect(page).toHaveURL(/\/login\?next=%2F$/)
  // open redirect attempt is ignored
  await page.goto('/login?next=' + encodeURIComponent('https://evil.example/'))
  await uiLogin(page, s.email)
  await dismissPasskeyOffer(page)
  await expect(page).toHaveURL(/localhost:5173\/(signup\/pending)?$/)
})

test('lockout path: 2 tries left, last try + captcha, lock + Locked email', async ({ page, request }) => {
  const s = await createSeller(request)
  await page.goto('/login')
  const fail = async () => { await uiLogin(page, s.email, 'Wrong-Passw0rd!xx'); }
  await fail(); await expect(page.getByRole('alert').filter({ hasText: 'Login failed' })).toBeVisible()
  await fail()
  await fail()
  await expect(page.getByText(/2 tries left/)).toBeVisible()
  await fail()
  await expect(page.getByText(/Last try/)).toBeVisible()
  await expect(page.getByRole('button', { name: 'Sign in', exact: true })).toBeDisabled() // Turnstile required
  await page.getByRole('button', { name: /Verify you are human/ }).click()
  await page.getByLabel('Password', { exact: true }).fill('Wrong-Passw0rd!xx')
  await page.getByRole('button', { name: 'Sign in', exact: true }).click()
  await expect(page.getByText(/Account locked/)).toBeVisible()
  expect(await lastMail(request, s.email, 'locked')).toContain('locked')
  // correct password is refused while locked
  await page.getByRole('button', { name: /Verify you are human/ }).click()
  await page.getByLabel('Password', { exact: true }).fill(PASSWORD)
  await page.getByRole('button', { name: 'Sign in', exact: true }).click()
  await expect(page).toHaveURL(/\/login/)
  await expect(page.getByText(/Login failed/)).toBeVisible()
})

test('forgot and reset password', async ({ page, request }) => {
  const s = await createSeller(request)
  await page.goto('/login')
  await page.getByRole('link', { name: 'Forgot password?' }).click()
  // Wait for the route change first: until then getByLabel('Email') still resolves to the outgoing Login form,
  // the fill is lost on unmount and the Forgot form is submitted empty (no request is ever sent).
  await expect(page.getByRole('heading', { name: 'Reset your password' })).toBeVisible()
  await page.getByLabel('Email').fill(s.email)
  const [forgot] = await Promise.all([
    page.waitForResponse((r) => r.url().includes('/auth/forgot-password')),
    page.getByRole('button', { name: 'Send reset link' }).click(),
  ])
  expect(forgot.status(), await forgot.text()).toBe(202)
  await expect(page.getByText(/reset link is on its way/)).toBeVisible()
  const mail = await lastMail(request, s.email, 'reset-password')
  const link = /http:\/\/localhost:5173\/reset-password\?[^\s]+/.exec(mail)![0]
  await page.goto(link)
  await page.getByLabel('New password', { exact: true }).fill('weak')
  await page.getByLabel('Confirm new password').fill('weak')
  await page.getByRole('button', { name: 'Reset password' }).click()
  await expect(page.getByText('Password does not meet the requirements')).toBeVisible()
  const newPw = 'N3w-Marble-Fox-Pass!'
  await page.getByLabel('New password', { exact: true }).fill(newPw)
  await page.getByLabel('Confirm new password').fill(newPw)
  await page.getByRole('button', { name: 'Reset password' }).click()
  await expect(page).toHaveURL(/\/login/)
  expect(await lastMail(request, s.email, 'password-changed')).toContain('Password changed')
  // link is single use
  await page.goto(link)
  await page.getByLabel('New password', { exact: true }).fill('An0ther-Marble-Fox!')
  await page.getByLabel('Confirm new password').fill('An0ther-Marble-Fox!')
  await page.getByRole('button', { name: 'Reset password' }).click()
  await expect(page.getByText(/invalid or has expired/)).toBeVisible()
  await page.goto('/login')
  await uiLogin(page, s.email, newPw)
  await dismissPasskeyOffer(page)
  await expect(page).not.toHaveURL(/\/login/)
})

