test('a delivery problem is flagged on the order, the list and the dashboard, and can be marked as handled', async ({ page, request }) => {
  const s = await seller(request)
  await product(request, s.token, 'Problem mug')
  const { packageId } = await shippingSetup(request, s.token)
  const o = await acceptedOrder(request, s.token)
  const label = await buyLabel(request, s.token, o.id, packageId)
  expect(await track(request, label.trackingNumber, 'failure', 'Address not found')).toBe('applied')
  await signIn(page, s.email, '/orders?tab=all')
  await expect(page.locator('.stats .stat', { hasText: 'Delivery problems' }).locator('.v')).toHaveText('1')
  await expect(page.locator('.chip', { hasText: 'Delivery problem' }).first()).toBeVisible()
  await page.getByText('More filters').click(); await page.getByLabel('Delivery progress').selectOption('exception')
  await expect(page.getByRole('link', { name: o.number }).first()).toBeVisible(); await expectNoSeriousA11y(page)
  await page.getByRole('link', { name: o.number }).first().click()
  await expect(page.getByText('Delivery problem – needs attention')).toBeVisible()
  await expect(page.getByText(/This order needs attention\./)).toBeVisible(); await expectNoSeriousA11y(page)
  await page.getByRole('button', { name: 'Mark as handled' }).click()
  await expect(page.getByText('Marked as handled.')).toBeVisible()
  await expect(page.getByText('Delivery problem – needs attention')).toHaveCount(0)
})

