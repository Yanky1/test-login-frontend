test('configure shipping, buy a label, print it, follow tracking to delivered (axe on every screen)', async ({ page, request }) => {
  const s = await seller(request)
  await product(request, s.token, 'Speckled mug')
  await signIn(page, s.email, '/settings/shipping')
  await expect(page.getByRole('heading', { name: 'Ship-from addresses' })).toBeVisible()
  await expectNoSeriousA11y(page)

  // address
  await page.getByRole('button', { name: 'Add an address' }).click()
  const ad = page.getByRole('dialog', { name: 'Add a ship-from address' })
  await ad.getByRole('button', { name: 'Save address' }).click()
  await expect(ad.getByText('Enter a contact name.')).toBeVisible()
  await ad.getByLabel('Name for this address').fill('Warehouse'); await ad.getByLabel('Contact name').fill('Acme Shop'); await ad.getByLabel('Address line 1').fill('10 Warehouse Rd')
  await ad.getByLabel('City').fill('Brooklyn'); await ad.getByLabel('State or region').fill('NY'); await ad.getByLabel('ZIP or postal code').fill('11201')
  await expectNoSeriousA11y(page)
  await ad.getByRole('button', { name: 'Save address' }).click()
  await expect(page.getByText('Address saved.')).toBeVisible(); await expect(page.getByText('Address verified')).toBeVisible(); await expect(page.getByText('Default', { exact: true }).first()).toBeVisible()
  // package
  await page.getByRole('button', { name: 'Add a package' }).click()
  const pk = page.getByRole('dialog', { name: 'Add a package' })
  await pk.getByLabel('Name').fill('Medium box'); await pk.getByLabel('Length (mm)').fill('300'); await pk.getByLabel('Width (mm)').fill('200'); await pk.getByLabel('Height (mm)').fill('150')
  await pk.getByRole('button', { name: 'Save package' }).click()
  await expect(page.getByText('Package saved.')).toBeVisible(); await expect(page.getByRole('region', { name: 'Package presets' }).locator('strong', { hasText: 'Medium box' })).toBeVisible()
  // rates
  await page.getByRole('button', { name: 'Add a rate profile' }).click()
  const pr = page.getByRole('dialog', { name: 'Add a rate profile' })
  await pr.getByLabel(/Free shipping from/).fill('75'); await expectNoSeriousA11y(page)
  await pr.getByRole('button', { name: 'Save profile' }).click()
  await expect(page.getByText('Rate profile saved.')).toBeVisible(); await expect(page.getByText(/Free shipping from \$75\.00/)).toBeVisible()
  // handling time
  await page.getByRole('spinbutton', { name: /Handling time/ }).fill('3'); await page.getByRole('button', { name: 'Save', exact: true }).click()
  await expect(page.getByText('Handling and returns saved.')).toBeVisible()
  await expectNoSeriousA11y(page)

  // buy a label for an accepted order
  const o = await acceptedOrder(request, s.token)
  await page.goto(`/orders/${o.id}`)
  await page.getByRole('button', { name: 'Ship order' }).first().click()
  const dlg = page.getByRole('dialog', { name: /^Ship order SO-/ })
  await expect(dlg.getByRole('tab', { name: 'Buy label', selected: true })).toBeVisible(); await expect(dlg.getByRole('tab', { name: 'Enter tracking manually' })).toBeVisible()
  await dlg.getByLabel(/Weight of the items/).fill('500')
  await dlg.getByRole('button', { name: 'Get shipping rates' }).click()
  await expect(dlg.getByText('Recommended')).toBeVisible(); await expect(dlg.getByRole('radio')).toHaveCount(4)
  await expectNoSeriousA11y(page)
  await dlg.getByRole('button', { name: /^Buy label · / }).click()
  await expect(dlg.getByText(/^Label bought for/)).toBeVisible()
  const tn = (await dlg.locator('dd').filter({ hasText: /^\d{10,}$/ }).first().textContent())!.trim()
  const [popup] = await Promise.all([page.waitForEvent('popup'), dlg.getByRole('button', { name: 'Print label' }).click()])
  expect(popup.url()).toMatch(/^blob:/); await popup.close()
  await expectNoSeriousA11y(page)
  await dlg.getByRole('button', { name: 'Done' }).click()
  await expect(page.getByText('Shipped', { exact: true }).first()).toBeVisible()
  const panel = page.getByRole('region', { name: 'Tracking and labels' }).or(page.locator('section', { has: page.getByRole('heading', { name: 'Tracking and labels' }) }))
  await expect(panel.getByRole('button', { name: 'Print label' })).toBeVisible()

  // tracking: in transit, then delivered (signed webhooks through the real pipeline)
  expect(await track(request, tn, 'in_transit', 'Departed facility')).toBe('applied')
  await page.reload()
  await expect(page.getByRole('list', { name: new RegExp(`Tracking history of ${tn}`) }).getByText('Departed facility')).toBeVisible()
  await expect(page.getByText('In transit').first()).toBeVisible()
  await expectNoSeriousA11y(page)
  await new Promise((r) => setTimeout(r, 1100))
  expect(await track(request, tn, 'delivered')).toBe('applied')
  await page.reload()
  await expect(page.getByText('Delivered', { exact: true }).first()).toBeVisible()
  await expect(page.getByRole('list', { name: new RegExp(`Tracking history of ${tn}`) }).getByText('Delivered').first()).toBeVisible()
  await expect(page.getByRole('button', { name: 'Void label' })).toHaveCount(1)   // still listed; the carrier decides whether it can be refunded
  await expectNoSeriousA11y(page)
})

test('void a label: refund is pending until the carrier confirms, then the order can be shipped again', async ({ page, request }) => {
  const s = await seller(request)
  await product(request, s.token, 'Void mug')
  const { packageId } = await shippingSetup(request, s.token)
  const o = await acceptedOrder(request, s.token)
  await buyLabel(request, s.token, o.id, packageId)
  await signIn(page, s.email, `/orders/${o.id}`)
  await page.getByRole('button', { name: /^Void label/ }).click()
  const d = page.getByRole('dialog', { name: 'Void this label?' })
  await expect(d.getByText(/only when the carrier confirms the refund/)).toBeVisible(); await expectNoSeriousA11y(page)
  await d.getByRole('button', { name: 'Yes, void the label' }).click()
  await expect(page.getByText(/Refund requested/).first()).toBeVisible(); await expect(page.getByText('Refund pending')).toBeVisible()
  await runMaintenance(request)
  await page.reload()
  await expect(page.getByRole('button', { name: 'Ship order' }).first()).toBeVisible()      // the shipment is gone: ready to ship again
  await expect(page.locator('.chips-row')).not.toContainText('Shipped')
  await expectNoSeriousA11y(page)
})

